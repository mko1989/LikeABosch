#!/usr/bin/env node
// Generates docs/protocol/conference/REFERENCE.md from operations/*.json and types/*.json.
// Usage: node scripts/build-conference-reference.mjs   (never edit REFERENCE.md by hand)
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const base = join(root, 'docs/protocol/conference');
const readDir = dir => readdirSync(join(base, dir)).filter(f => f.endsWith('.json')).sort()
  .map(f => JSON.parse(readFileSync(join(base, dir, f), 'utf8')));
const ops = readDir('operations');
const types = readDir('types');

const CATEGORY_ORDER = ['auth', 'system', 'events', 'permissions', 'meeting', 'agenda', 'discussion', 'seats', 'participants',
  'voting', 'interpretation', 'presentation', 'volume', 'power', 'illumination', 'room', 'files', 'images', 'notes',
  'plugins', 'license', 'token'];

/** Render type notation as indented pseudo-JSON. */
function render(v, indent = '') {
  if (typeof v === 'string') return v.startsWith('enum:') ? v.slice(5).split('|').map(s => `"${s}"`).join(' | ') : `<${v.replace(/^ref:/, '')}>`;
  if (Array.isArray(v)) return `[ ${render(v[0], indent)} ]`;
  const entries = Object.entries(v);
  if (!entries.length) return '{}';
  const inner = indent + '  ';
  return `{\n${entries.map(([k, x]) => `${inner}"${k}": ${render(x, inner)}`).join(',\n')}\n${indent}}`;
}

const anchor = s => s.toLowerCase().replace(/[^a-z0-9]+/g, '-');
const out = [];
out.push('# Conference Protocol — operation reference', '',
  '> Generated by `node scripts/build-conference-reference.mjs` from `operations/*.json` and `types/*.json`. **Do not edit by hand.**',
  '> Protocol basics: [README.md](README.md). Notation: `<string>` primitive, `"a" | "b"` enum, `[ x ]` array.', '');

const inScope = ops.filter(o => !o.excluded);
const byCat = new Map(CATEGORY_ORDER.map(c => [c, []]));
for (const o of inScope) byCat.get(o.category).push(o);

out.push(`${inScope.length} operations in scope, ${ops.length - inScope.length} excluded (DEC-007).`, '', '## Contents', '');
for (const [cat, list] of byCat) if (list.length) out.push(`- **${cat}**: ${list.map(o => `[${o.operation}](#${anchor(o.operation)})`).join(', ')}`);
out.push('- [Types](#types)', '- [Excluded operations](#excluded-operations)', '');

for (const [cat, list] of byCat) {
  if (!list.length) continue;
  out.push(`## ${cat}`, '');
  for (const o of list) {
    out.push(`### ${o.operation}`, '');
    if (o.summary) out.push(o.summary, '');
    const req = [];
    if (o.permissions.length) req.push(`permissions: ${o.permissions.map(p => `\`${p}\``).join(', ')}`);
    if (o.licenses.length) req.push(`licences: ${o.licenses.map(p => `\`${p}\``).join(', ')}`);
    if (req.length) out.push(`Requires ${req.join('; ')}.`, '');
    out.push('Request parameters:', '```', render(o.request), '```', 'Response parameters:', '```', render(o.response), '```');
    if (o.remarks) out.push('', `Remarks: ${o.remarks}`);
    if (o.extractionNotes) out.push('', `> Note: ${o.extractionNotes}`);
    const meta = [o.sourcePages ? `PDF pp. ${o.sourcePages.join('–')}` : `source: ${o.source}`];
    if (o.seeAlso.length) meta.push(`see also ${o.seeAlso.map(s => `[${s}](#${anchor(s)})`).join(', ')}`);
    out.push('', `<sub>${meta.join(' · ')}</sub>`, '');
  }
}

out.push('## Types', '');
for (const t of types) {
  out.push(`### ${t.name}`, '', `*${t.kind}${t.wrapper ? ', request/response wrapper' : ''}*${t.summary ? ': ' + t.summary : ''}`, '');
  if (t.members.length) {
    out.push('| Member | Value | Description |', '|---|---|---|');
    t.members.forEach(m => out.push(`| \`${m.name}\` | ${m.value ?? ''} | ${m.description ?? ''} |`));
    out.push('');
  }
  if (t.fields.length) {
    out.push('| Field | Type | Description |', '|---|---|---|');
    t.fields.forEach(f => out.push(`| \`${f.name}\` | ${f.type ? '`' + JSON.stringify(f.type) + '`' : ''} | ${f.description ?? ''} |`));
    out.push('');
  }
}

out.push('## Excluded operations', '');
ops.filter(o => o.excluded).forEach(o => out.push(`- **${o.operation}**: ${o.excluded}`));
out.push('');

writeFileSync(join(base, 'REFERENCE.md'), out.join('\n'));
console.log(`REFERENCE.md written: ${inScope.length} operations, ${types.length} types`);
